pub const HEADER_START: [u8; 4] = [0xF1, 0x01, 0xEE, 0xEE];
pub const HEADER_END: [u8; 4] = [0xFF, 0x01, 0xEE, 0xEE];

pub struct HeaderSection {
    pub tile_count: i32,
    pub base_width: i32,
    pub base_height: i32,
    pub scan_scale: i32,
    pub spend_time: i32,
    pub scan_time: i64,
    pub image_cap_res: f32,
    pub tile_size: i32,
}

impl Default for HeaderSection {
    fn default() -> Self {
        Self {
            tile_count: 1,
            base_width: 256,
            base_height: 256,
            scan_scale: 20,
            spend_time: 0,
            scan_time: 0,
            image_cap_res: 0.25,
            tile_size: 256,
        }
    }
}

pub fn make_header_section(section: HeaderSection) -> Vec<u8> {
    let mut buf = Vec::new();
    buf.extend_from_slice(&HEADER_START); // bytes 0-3
    buf.extend_from_slice(&[0u8; 12]); // bytes 4-15: padding/version
    buf.write_i32::<LittleEndian>(section.tile_count).unwrap();
    buf.write_i32::<LittleEndian>(section.base_height).unwrap();
    buf.write_i32::<LittleEndian>(section.base_width).unwrap();
    buf.write_i32::<LittleEndian>(section.scan_scale).unwrap();
    buf.extend_from_slice(b"JPEG");
    buf.write_i32::<LittleEndian>(section.spend_time).unwrap();
    buf.write_i64::<LittleEndian>(section.scan_time).unwrap();
    buf.extend_from_slice(&[0u8; 4]); // bytes 48-51: skip
    buf.write_i32::<LittleEndian>(section.tile_size).unwrap(); // bytes 52-55
    buf.extend_from_slice(&[0u8; 20]); // bytes 56-75: skip
    buf.write_f32::<LittleEndian>(section.image_cap_res)
        .unwrap(); // bytes 76-79
    // pad content to 88 bytes (96 total - 4 start - 4 end), then end marker
    let content_so_far = buf.len() - 4; // subtract start marker
    if content_so_far < 88 {
        buf.extend(std::iter::repeat_n(0u8, 88 - content_so_far));
    }
    buf.extend_from_slice(&HEADER_END);
    assert_eq!(buf.len(), 96, "header section must be exactly 96 bytes");
    buf
}

pub const THUMBNAIL_START: [u8; 4] = [0xF1, 0x02, 0xEE, 0xEE];
pub const LABEL_START: [u8; 4] = [0xF1, 0x03, 0xEE, 0xEE];

pub fn make_associated_image_section(
    start_marker: [u8; 4],
    width: i32,
    height: i32,
    data_length: i32,
) -> Vec<u8> {
    let mut buf = Vec::new();
    buf.extend_from_slice(&start_marker); // bytes 0-3
    buf.extend_from_slice(&[0u8; 4]); // bytes 4-7: skip
    buf.write_i32::<LittleEndian>(height).unwrap(); // bytes 8-11
    buf.write_i32::<LittleEndian>(width).unwrap(); // bytes 12-15
    buf.write_i32::<LittleEndian>(3).unwrap(); // bytes 16-19: samples per pixel
    buf.write_i32::<LittleEndian>(data_length).unwrap(); // bytes 20-23
    buf.write_i32::<LittleEndian>(52).unwrap(); // bytes 24-27: header length
    // pad to exactly 52 bytes
    assert!(buf.len() <= 52);
    buf.extend(std::iter::repeat_n(0u8, 52 - buf.len()));
    assert_eq!(buf.len(), 52);
    buf
}

pub const TILE_INFO_START: [u8; 4] = [0xF1, 0x04, 0xEE, 0xEE];
pub const TILE_INFO_END: [u8; 4] = [0xFF, 0x04, 0xEE, 0xEE];

/// Build the bytes that go at offset `0xa8` in a KFBF header to describe channel metadata.
///
/// Layout:
///   - Three 16-byte TLV entries for tags 0x4d (names), 0x4f (colors), 0x54 (exposures)
///   - Immediately after: name block, color block, exposure block
///
/// Each TLV entry: 4-byte BE tag + 4-byte BE len (8) + 8-byte value where
/// bytes [3..7] hold the file offset as LE u32.
pub fn make_kfbf_channel_metadata_block(
    names: &[&str],
    colors: &[[u8; 3]],
    exposures: &[f64],
) -> Vec<u8> {
    let n = names.len();
    assert_eq!(colors.len(), n);
    assert_eq!(exposures.len(), n);

    // TLV block starts at file offset 0xa8.
    // Three TLV entries × 16 bytes each = 48 bytes of TLV header.
    let tlv_base: u32 = 0xa8;
    let names_offset: u32 = tlv_base + 48;
    let colors_offset: u32 = names_offset + (n as u32) * 40;
    let exposures_offset: u32 = colors_offset + (n as u32) * 12;

    let mut buf: Vec<u8> = Vec::new();

    let write_tlv = |buf: &mut Vec<u8>, tag: u32, offset: u32| {
        buf.write_u32::<BigEndian>(tag).unwrap(); // tag
        buf.write_u32::<BigEndian>(8).unwrap(); // len = 8
        buf.write_u8(0).unwrap(); // value bytes [0..2]: zero padding
        buf.write_u8(0).unwrap();
        buf.write_u8(0).unwrap();
        buf.write_u32::<LittleEndian>(offset).unwrap(); // value bytes [3..7]: LE u32 offset
        buf.write_u8(0).unwrap(); // value byte [7]: zero padding
    };

    write_tlv(&mut buf, 0x4d, names_offset);
    write_tlv(&mut buf, 0x4f, colors_offset);
    write_tlv(&mut buf, 0x54, exposures_offset);

    // Name block: n × 40-byte null-padded ASCII strings
    for name in names {
        let bytes = name.as_bytes();
        assert!(bytes.len() <= 40, "channel name too long");
        buf.extend_from_slice(bytes);
        buf.extend(std::iter::repeat_n(0u8, 40 - bytes.len()));
    }

    // Color block: n × 3 × LE u32
    for color in colors {
        buf.write_u32::<LittleEndian>(color[0] as u32).unwrap();
        buf.write_u32::<LittleEndian>(color[1] as u32).unwrap();
        buf.write_u32::<LittleEndian>(color[2] as u32).unwrap();
    }

    // Exposure block: n × LE f64
    for &exp in exposures {
        buf.write_f64::<LittleEndian>(exp).unwrap();
    }

    buf
}

/// Build a tile info section matching the real KFB binary layout.
/// `y_native`: y-pixel coordinate at native resolution (byte 8).
/// `tile_w`: tile width in pixels (byte 12).
/// `tile_h`: tile height in pixels (byte 16).
/// `magnification`: zoom magnification as f32 (byte 20); 20.0 = full resolution.
pub fn make_tile_info_section(
    y_native: i32,
    tile_w: i32,
    tile_h: i32,
    magnification: f32,
    data_length: i32,
    offset_from_file: i64,
) -> Vec<u8> {
    let mut buf = Vec::new();
    buf.extend_from_slice(&TILE_INFO_START);
    buf.extend_from_slice(&[0u8; 4]); // skip 4
    buf.write_i32::<LittleEndian>(y_native).unwrap();
    buf.write_i32::<LittleEndian>(tile_w).unwrap();
    buf.write_i32::<LittleEndian>(tile_h).unwrap();
    buf.write_f32::<LittleEndian>(magnification).unwrap();
    buf.write_i32::<LittleEndian>(0).unwrap(); // unused, always 0
    buf.extend_from_slice(&[0u8; 4]); // skip 4
    buf.write_i32::<LittleEndian>(data_length).unwrap();
    buf.write_i64::<LittleEndian>(offset_from_file).unwrap();
    buf.extend_from_slice(&[0u8; 16]); // skip 16
    buf.extend_from_slice(&TILE_INFO_END);
    buf
}
